// 1. Define an array named fruits
let fruits = ["apple", "banana", "mango", "orange"];

// 2. Print the first fruit by its index
console.log("First fruit:", fruits[0]);

// 3. Push another fruit into the array
fruits.push("pineapple");

// 4. Loop through the array using a for loop and print each fruit
for (let i = 0; i < fruits.length; i++) {
  console.log("Fruit " + i + ":", fruits[i]);
}